pub fn translate(code: c_int) Error!void {
    if (errorFromCode(code)) |err| return err;
}

test "translate returns the most specific error" {
    try translate(c.SQLITE_OK);
    try translate(c.SQLITE_ROW);
    try translate(c.SQLITE_DONE);
    try translate(c.SQLITE_OK_LOAD_PERMANENTLY);
    try std.testing.expectError(error.Busy, translate(c.SQLITE_BUSY));
    try std.testing.expectError(error.BusyTimeout, translate(c.SQLITE_BUSY_TIMEOUT));
    try std.testing.expectError(error.ConstraintUnique, translate(c.SQLITE_CONSTRAINT_UNIQUE));
    try std.testing.expectError(error.Ioerr, translate(c.SQLITE_IOERR));
    try std.testing.expectError(error.IoerrFsync, translate(c.SQLITE_IOERR_FSYNC));
    try std.testing.expectError(error.Unknown, translate(99));
    // unknown extended bits fall back to the primary code
    try std.testing.expectError(error.Busy, translate(c.SQLITE_BUSY | (99 << 8)));
}
